import express from 'express';
import { createServer } from 'http';
import path from 'path';
import cors from 'cors';
import { ENV } from './config/env.js';
import { ubotWebhookRouter } from './routes/ubotWebhook.js';
import { pipelineRouter } from './routes/pipelineRoutes.js';
import { ubotRouter } from './routes/ubotRoutes.js';
import { adminRouter } from './routes/adminRoutes.js';
import { tokenomistRouter } from './routes/tokenomistRoutes.js';
import { avalancheService } from './services/avalancheService.js';
import { elevenlabsService } from './services/elevenlabsService.js';
import { tokenomistService } from './services/tokenomistService.js';
import { telemetrySocketService } from './services/telemetrySocket.js';
import { sessionStore } from './services/sessionStore.js';
import { fallbackCacheService } from './services/fallbackCache.js';
import { resilientRpcProvider } from './config/resilientRpc.js';
import { elevenlabsCircuitBreaker } from './middleware/circuitBreaker.js';
import { initProcessErrorTraps, globalErrorHandler } from './middleware/errorHandler.js';

// Initialize zero-crash process-level error traps
initProcessErrorTraps();

const app = express();
const server = createServer(app);

// Enable CORS for frontend and external integrations
app.use(cors({ origin: true, credentials: true }));

app.use(express.json());
app.use(express.urlencoded({ extended: true }));

// Serve static audio files generated by ElevenLabs
app.use('/audio', express.static(path.resolve(process.cwd(), 'public', 'audio')));

// Serve frontend static build if built
const frontendDist = path.resolve(process.cwd(), 'frontend', 'dist');
app.use(express.static(frontendDist));

// Health check endpoint with live telemetry diagnostics
app.get('/health', async (_req, res) => {
  try {
    const avalanche = await avalancheService.ping();
    const fallbackActive = fallbackCacheService.isFallbackActive();
    const rpcInfo = resilientRpcProvider.getActiveEndpoint();
    const voiceStatus = elevenlabsCircuitBreaker.getStatusSummary();

    res.json({
      status: 'ok',
      service: 'flowagent-core',
      sprint: 'Sprint 3: Zero-Crash Hardening & Failure Proofing',
      timestamp: new Date().toISOString(),
      fallback: {
        active: fallbackActive,
        label: fallbackActive ? '🟠 OFFLINE CACHE (PANIC ACTIVE)' : '🟢 LIVE ON-CHAIN',
      },
      websocket: {
        activeClients: telemetrySocketService.getConnectedClientCount(),
        path: '/ws',
      },
      sessions: {
        activeCount: sessionStore.getAllSessions().length,
      },
      avalanche: {
        isFuji: avalanche.isFuji,
        chainId: avalanche.chainId.toString(),
        blockNumber: avalanche.blockNumber,
        gasPrice: avalanche.gasPrice,
        activeNode: rpcInfo.name,
        rpcLatencyMs: avalanche.rpcLatencyMs,
        isFallbackMode: avalanche.isFallbackMode,
      },
      elevenlabs: {
        configured: elevenlabsService.isConfigured(),
        voiceId: ENV.ELEVENLABS_VOICE_ID,
        circuitBreaker: voiceStatus,
      },
      tokenomist: {
        active: true,
        configured: tokenomistService.isConfigured(),
        status: 'READY',
      },
    });
  } catch (err: any) {
    res.status(503).json({
      status: 'degraded',
      error: err.message,
    });
  }
});

// Direct ElevenLabs TTS synthesis endpoint (Partner Ecosystem requirement)
app.post('/api/elevenlabs/tts', async (req, res) => {
  try {
    const { text, voiceId } = req.body;
    if (!text) {
      res.status(400).json({ success: false, error: 'Text prompt is required for TTS synthesis.' });
      return;
    }

    const ttsRes = await elevenlabsService.synthesizeSpeech(text, {
      voiceId,
      saveToFile: true,
      timeoutMs: 1200,
    });

    if (ttsRes.success && ttsRes.outputPath) {
      const fileName = path.basename(ttsRes.outputPath);
      res.json({
        success: true,
        audioUrl: `/audio/${fileName}`,
        bytesCount: ttsRes.bytesCount,
      });
      return;
    }

    res.status(502).json({
      success: false,
      error: ttsRes.error || 'ElevenLabs TTS synthesis failed or timed out.',
      degraded: ttsRes.degraded,
    });
  } catch (err: any) {
    res.status(500).json({
      success: false,
      error: err.message || 'Internal server error during TTS synthesis.',
    });
  }
});

// Mount Routes
app.use('/api/pipeline', pipelineRouter);
app.use('/api/webhook/ubot', ubotWebhookRouter);
app.use('/api/ubot', ubotRouter);
app.use('/api/admin', adminRouter);
app.use('/api/tokenomist', tokenomistRouter);

// Fallback for SPA routing to index.html
app.get('*', (req, res, next) => {
  if (req.path.startsWith('/api') || req.path.startsWith('/ws') || req.path.startsWith('/audio') || req.path.startsWith('/health')) {
    return next();
  }
  const indexPath = path.resolve(frontendDist, 'index.html');
  res.sendFile(indexPath);
});

// Register Global Error Handler (Must be after all route handlers)
app.use(globalErrorHandler);

// Initialize WebSocket Telemetry Engine
telemetrySocketService.init(server, '/ws');

// Determine if app is run directly or imported into a test runner
const isDirectRun = Boolean(
  process.argv[1] &&
    (process.argv[1].endsWith('app.ts') || process.argv[1].endsWith('app.js')) &&
    process.env.NODE_ENV !== 'test'
);

if (isDirectRun) {
  const PORT = ENV.PORT;
  server.listen(PORT, () => {
    console.log(`🚀 FlowAgent OS Core server running on http://localhost:${PORT}`);
    console.log(`📡 WebSocket Telemetry: ws://localhost:${PORT}/ws`);
    console.log(`🔗 Avalanche Fuji RPC: ${ENV.AVALANCHE_RPC_URL}`);
    console.log(`🎙️ ElevenLabs Voice: ${elevenlabsService.isConfigured() ? 'ACTIVE (Turbo v2.5)' : 'STANDBY'}`);
    console.log(`📊 Tokenomist Intelligence: ACTIVE (Token Unlock & Vesting Data)`);
    console.log(`🤖 U-Bot Controller: http://localhost:${PORT}/api/ubot/message`);
    console.log(`⚡ Execution Pipeline: http://localhost:${PORT}/api/pipeline/execute`);
  });
}

export { app, server };
export default app;
